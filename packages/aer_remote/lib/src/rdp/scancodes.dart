/// RDP scancode for a Flutter `usbHidUsage`, or null when unknown.
int? rdpScancodeForHid(int usbHidUsage) =>
    (usbHidUsage >> 16) == 0x7 ? hidToRdpScancode[usbHidUsage & 0xFFFF] : null;

/// Pointer flags (MS-RDPBCGR 2.2.8.1.1.3.1.1.3).
abstract final class RdpPointer {
  static const move = 0x0800;
  static const down = 0x8000;
  static const button1 = 0x1000; // left
  static const button2 = 0x2000; // right
  static const button3 = 0x4000; // middle
  static const wheel = 0x0200;
  static const hwheel = 0x0400;
  static const wheelNegative = 0x0100;

  /// Wheel flags for a delta in notches×120 (positive = away from user).
  static int wheelFlags(int delta, {bool horizontal = false}) {
    final d = delta.clamp(-255, 255);
    final base = horizontal ? hwheel : wheel;
    return d < 0
        ? base | wheelNegative | ((256 + d) & 0xFF)
        : base | (d & 0xFF);
  }
}
